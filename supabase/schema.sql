CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.prevent_profile_role_escalation()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF public.current_app_profile_id() IS NULL OR public.is_admin() THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'INSERT' AND NEW.role NOT IN ('user', 'parent', 'student') THEN
    RAISE EXCEPTION 'Not authorized to create privileged profile role';
  END IF;

  IF TG_OP = 'UPDATE' AND NEW.role IS DISTINCT FROM OLD.role THEN
    RAISE EXCEPTION 'Not authorized to change profile role';
  END IF;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.force_product_pending_status()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF public.current_user_role() = 'publisher' AND NOT public.has_role(ARRAY['super_admin', 'general_supervisor', 'enha_lak_supervisor']) THEN
    NEW.approval_status := 'pending';
    NEW.is_active := FALSE;
    NEW.publisher_id := public.current_app_profile_id();
  END IF;
  RETURN NEW;
END;
$$;

DO $$
DECLARE
  target_table TEXT;
BEGIN
  FOREACH target_table IN ARRAY ARRAY[
    'profiles', 'child_profiles', 'instructors', 'publisher_profiles',
    'personalized_products', 'creative_writing_packages', 'standalone_services',
    'subscription_plans', 'orders', 'subscriptions', 'service_orders', 'bookings',
    'scheduled_sessions', 'blog_posts', 'support_tickets', 'join_requests',
    'support_session_requests'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS update_%s_updated_at ON public.%I', target_table, target_table);
    EXECUTE format('CREATE TRIGGER update_%s_updated_at BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column()', target_table, target_table);
  END LOOP;
END $$;

